'use strict';

/**
 * ES5 page script for the loading-card notice. The returned string is what
 * runs inside Foundry. It must not use arrows, template literals, let, or const.
 * The admin note is embedded as a JSON string literal.
 */

/**
 * @param {unknown} message
 * @returns {string}
 */
function buildSlowCacheNoticeScript(message) {
  const text = typeof message === 'string' ? message : '';
  const literal = JSON.stringify(text);
  const source = [
    '(function () {',
    "  'use strict';",
    '  try {',
    '    if (window.__flcSlowCache) return;',
    '    var MESSAGE = __FLC_MESSAGE__;',
    "    var ROOT_ID = 'flc-slow-cache';",
    "    var STYLE_ID = 'flc-slow-cache-style';",
    '    var observer = null;',
    '    var watching = false;',
    '    var destroyed = false;',
    '    var seen = false;',
    '    var busy = false;',
    '    var copiedTimer = 0;',
    '',
    '    function hasClass(el, name) {',
    "      var cls = '';",
    '      if (!el || !name) return false;',
    '      try {',
    "        cls = String(el.className || (el.getAttribute && el.getAttribute('class')) || '');",
    '      } catch (e) { cls = ""; }',
    "      return (' ' + cls + ' ').indexOf(' ' + name + ' ') !== -1;",
    '    }',
    '',
    '    function overlay() {',
    '      var root = null;',
    "      try { root = document.getElementById('fvtt-loading-progress'); } catch (e) { root = null; }",
    '      return root;',
    '    }',
    '',
    '    function finished(root) {',
    '      if (!root) return true;',
    '      if (!document.body || !document.body.contains(root)) return true;',
    "      return hasClass(root, 'flp-finished');",
    '    }',
    '',
    '    function findCard(root) {',
    '      var nodes = [];',
    '      var i = 0;',
    '      if (!root || typeof root.querySelectorAll !== "function") return null;',
    "      try { nodes = root.querySelectorAll('main'); } catch (e) { nodes = []; }",
    '      for (i = 0; i < nodes.length; i++) {',
    "        if (hasClass(nodes[i], 'flp-card')) return nodes[i];",
    '      }',
    '      try { return root.querySelector(".flp-card"); } catch (e2) { return null; }',
    '    }',
    '',
    '    function findHide(card) {',
    '      var nodes = [];',
    '      var i = 0;',
    '      var text = "";',
    '      if (!card || typeof card.querySelectorAll !== "function") return null;',
    "      try { nodes = card.querySelectorAll('a, button'); } catch (e) { nodes = []; }",
    '      for (i = 0; i < nodes.length; i++) {',
    '        if (!nodes[i] || nodes[i].id === ROOT_ID) continue;',
    '        text = "";',
    "        try { text = String(nodes[i].textContent || '').replace(/\\s+/g, ''); } catch (e2) { text = ''; }",
    "        if (text === 'Hide') return nodes[i];",
    '      }',
    '      return null;',
    '    }',
    '',
    '    function anchorAfter(card) {',
    '      var meta = null;',
    '      var track = null;',
    '      try { meta = card.querySelector(".flp-meta"); } catch (e) { meta = null; }',
    '      try { track = card.querySelector(".flp-track"); } catch (e2) { track = null; }',
    '      return meta || track || null;',
    '    }',
    '',
    '    function ensureStyle() {',
    '      var style = null;',
    '      var parent = null;',
    '      try { style = document.getElementById(STYLE_ID); } catch (e) { style = null; }',
    '      if (style) return;',
    "      style = document.createElement('style');",
    '      style.id = STYLE_ID;',
    "      style.textContent = '#flc-slow-cache{margin:0.75rem 0 0;padding:0.6rem 0.7rem;border:1px solid #e0a100;border-radius:8px;background:#2a2416;color:#f3e6c0;font:13px/1.4 sans-serif;text-align:left}#flc-slow-cache p{margin:0 0 0.35rem}#flc-slow-cache button{margin:0.25rem 0.4rem 0 0;padding:0.28rem 0.55rem;border-radius:6px;border:1px solid #e0a100;background:#3a3018;color:#f6d98a;cursor:pointer}#flc-slow-cache pre{max-height:9rem;overflow:auto;margin:0.45rem 0 0;padding:0.45rem;background:#161818;color:#e8e4d8;white-space:pre-wrap;font:11px/1.35 monospace}';",
    '      parent = document.head || document.documentElement || document.body;',
    '      if (parent) parent.appendChild(style);',
    '    }',
    '',
    '    function markCopied(button) {',
    "      var prev = button.getAttribute('data-label') || 'Copy message for your server admin';",
    "      button.textContent = 'Copied';",
    '      if (copiedTimer) clearTimeout(copiedTimer);',
    '      copiedTimer = setTimeout(function () { button.textContent = prev; }, 2000);',
    '    }',
    '',
    '    function fallbackCopy(value, button) {',
    '      var area = null;',
    '      var ok = false;',
    '      try {',
    "        area = document.createElement('textarea');",
    '        area.value = value;',
    "        area.setAttribute('readonly', 'readonly');",
    '        document.body.appendChild(area);',
    '        area.select();',
    "        if (typeof document.execCommand === 'function') ok = document.execCommand('copy') !== false;",
    '      } catch (e) { ok = false; }',
    '      if (area && area.parentNode) {',
    '        try { area.parentNode.removeChild(area); } catch (e2) {}',
    '      }',
    '      if (ok) markCopied(button);',
    '    }',
    '',
    '    function copyText(value, button) {',
    '      var pending = null;',
    '      if (navigator && navigator.clipboard && typeof navigator.clipboard.writeText === "function") {',
    '        try { pending = navigator.clipboard.writeText(value); } catch (e) { pending = null; }',
    '        if (pending && typeof pending.then === "function") {',
    '          pending.then(function () { markCopied(button); }, function () { fallbackCopy(value, button); });',
    '          return;',
    '        }',
    '      }',
    '      fallbackCopy(value, button);',
    '    }',
    '',
    '    function makeCard() {',
    "      var box = document.createElement('div');",
    "      var title = document.createElement('p');",
    "      var sentence = document.createElement('p');",
    "      var copy = document.createElement('button');",
    "      var details = document.createElement('button');",
    "      var pre = document.createElement('pre');",
    '      box.id = ROOT_ID;',
    "      box.setAttribute('class', 'flc-slow-cache');",
    "      title.setAttribute('class', 'flc-slow-cache-title');",
    "      title.textContent = 'Server configuration could be optimized';",
    "      sentence.setAttribute('class', 'flc-slow-cache-line');",
    "      sentence.textContent = 'The black screen is this server re-checking unchanged files one at a time before the loading bar can appear.';",
    "      copy.type = 'button';",
    "      copy.setAttribute('class', 'flc-slow-cache-copy');",
    "      copy.setAttribute('data-label', 'Copy message for your server admin');",
    "      copy.textContent = 'Copy message for your server admin';",
    '      copy.addEventListener("click", function () { copyText(MESSAGE, copy); });',
    "      details.type = 'button';",
    "      details.setAttribute('class', 'flc-slow-cache-details');",
    "      details.textContent = 'Details';",
    "      pre.setAttribute('class', 'flc-slow-cache-full');",
    '      pre.textContent = MESSAGE;',
    "      pre.style.display = 'none';",
    '      details.addEventListener("click", function () {',
    "        var open = pre.style.display !== 'none';",
    "        pre.style.display = open ? 'none' : 'block';",
    "        details.textContent = open ? 'Details' : 'Hide details';",
    '      });',
    '      box.appendChild(title);',
    '      box.appendChild(sentence);',
    '      box.appendChild(copy);',
    '      box.appendChild(details);',
    '      box.appendChild(pre);',
    '      return box;',
    '    }',
    '',
    '    function unmountNode() {',
    '      var node = null;',
    '      var style = null;',
    '      try { node = document.getElementById(ROOT_ID); } catch (e) { node = null; }',
    '      if (node && node.parentNode) {',
    '        try { node.parentNode.removeChild(node); } catch (e2) {}',
    '      }',
    '      try { style = document.getElementById(STYLE_ID); } catch (e3) { style = null; }',
    '      if (style && style.parentNode) {',
    '        try { style.parentNode.removeChild(style); } catch (e4) {}',
    '      }',
    '    }',
    '',
    '    function destroy() {',
    '      destroyed = true;',
    '      if (observer) {',
    '        try { observer.disconnect(); } catch (e) {}',
    '        observer = null;',
    '      }',
    '      watching = false;',
    '      if (copiedTimer) {',
    '        try { clearTimeout(copiedTimer); } catch (e2) {}',
    '        copiedTimer = 0;',
    '      }',
    '      unmountNode();',
    '    }',
    '',
    '    function mount() {',
    '      var root = null;',
    '      var card = null;',
    '      var existing = null;',
    '      var anchor = null;',
    '      var hide = null;',
    '      if (destroyed) return false;',
    '      root = overlay();',
    '      if (!root || finished(root)) {',
    '        if (seen) destroy();',
    '        return false;',
    '      }',
    '      card = findCard(root);',
    '      if (!card) return false;',
    '      seen = true;',
    '      try { ensureStyle(); } catch (e0) {}',
    '      try { existing = document.getElementById(ROOT_ID); } catch (e) { existing = null; }',
    '      if (existing && typeof card.contains === "function" && card.contains(existing)) return true;',
    '      if (!existing) existing = makeCard();',
    '      anchor = anchorAfter(card);',
    '      hide = findHide(card);',
    '      if (anchor && anchor.parentNode) {',
    '        try { anchor.parentNode.insertBefore(existing, anchor.nextSibling); } catch (e2) { return false; }',
    '      } else if (hide && hide.parentNode) {',
    '        try { hide.parentNode.insertBefore(existing, hide); } catch (e3) { return false; }',
    '      } else {',
    '        try { card.appendChild(existing); } catch (e4) { return false; }',
    '      }',
    '      return true;',
    '    }',
    '',
    '    function watch() {',
    "      if (watching || !document.body || typeof MutationObserver !== 'function') return;",
    '      observer = new MutationObserver(function () {',
    '        var root = null;',
    '        if (destroyed || busy) return;',
    '        try { root = overlay(); } catch (e0) { root = null; }',
    '        if (seen && finished(root)) { destroy(); return; }',
    '        if (seen) return;',
    '        busy = true;',
    '        try { mount(); } catch (e) {}',
    '        busy = false;',
    '      });',
    '      try {',
    "        observer.observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['class'] });",
    '        watching = true;',
    '      } catch (e2) {}',
    '    }',
    '',
    '    window.__flcSlowCache = {',
    '      mount: function () { try { return mount(); } catch (e) { return false; } },',
    '      destroy: function () { try { destroy(); } catch (e) {} }',
    '    };',
    '    try { watch(); } catch (e4) {}',
    '    try { mount(); } catch (e5) {}',
    '  } catch (e6) {}',
    '})();',
  ].join('\n');
  return source.split('__FLC_MESSAGE__').join(literal);
}

module.exports = {
  buildSlowCacheNoticeScript,
};
